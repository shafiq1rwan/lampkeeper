// Keyboard-only menu operation, Space never pausing, and a frozen simulation while paused.
import { chromium } from 'playwright-core';
const base = process.env.LK_URL ?? 'http://localhost:5173/';
const browser = await chromium.launch({ channel: process.env.LK_BROWSER ?? 'msedge', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const r = {};
const q = (fn) => page.evaluate(fn);
await page.goto(`${base}?shift=2`);
await page.waitForFunction(() => window.__lk?.game?.state === 'ready');
await page.keyboard.press('Enter');
await page.waitForTimeout(300);
r.startedWithEnter = await q(() => window.__lk.game.state);
await page.keyboard.press('Space');
await page.waitForTimeout(200);
r.spaceDoesNotPause = await q(() => window.__lk.game.menus.current === null);
await page.keyboard.press('Escape');
await page.waitForTimeout(200);
const t1 = await q(() => window.__lk.game.world.time);
await page.waitForTimeout(1200);
const t2 = await q(() => window.__lk.game.world.time);
r.pausedFreezesSim = t1 === t2;
r.focusOnOpen = await q(() => document.activeElement?.textContent);
await page.keyboard.press('ArrowDown');
await page.keyboard.press('ArrowDown');
r.focusAfterArrows = await q(() => document.activeElement?.textContent);
await page.keyboard.press('Enter');
await page.waitForTimeout(150);
r.openedWithEnter = await q(() => window.__lk.game.menus.current);
await page.keyboard.press('Escape');
await page.waitForTimeout(150);
r.escapeBack = await q(() => window.__lk.game.menus.current);
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
r.escapeResumes = await q(() => ({ menu: window.__lk.game.menus.current, paused: window.__lk.game.pause.paused }));
const t3 = await q(() => window.__lk.game.world.time);
await page.waitForTimeout(600);
r.simRunsAgain = (await q(() => window.__lk.game.world.time)) > t3;
console.log(JSON.stringify(r, null, 1));
await browser.close();
